// Regenerates src/data/project-images.ts from the folders in src/assets/projects.
// Each folder is a project slug containing cover.webp, thumb.webp, mobile.webp and optionally section.webp.
// Usage: node scripts/generate-image-map.mjs
import fs from "node:fs";

const ROOT = "src/assets/projects";
const KINDS = ["cover", "thumb", "mobile", "section"];

const toIdentifier = (slug, kind) =>
  "p" +
  slug.replace(/(^|-)(\w)/g, (_, __, char) => char.toUpperCase()) +
  kind[0].toUpperCase() +
  kind.slice(1);

let imports = "";
let entries = "";

for (const slug of fs.readdirSync(ROOT).sort()) {
  const files = fs.readdirSync(`${ROOT}/${slug}`).map((file) => file.replace(/\.webp$/, ""));
  const kinds = KINDS.filter((kind) => files.includes(kind));
  for (const kind of kinds) {
    imports += `import ${toIdentifier(slug, kind)} from "@/assets/projects/${slug}/${kind}.webp";\n`;
  }
  entries += `  "${slug}": { ${kinds.map((kind) => `${kind}: ${toIdentifier(slug, kind)}`).join(", ")} },\n`;
}

fs.writeFileSync(
  "src/data/project-images.ts",
  `// Generated by scripts/generate-image-map.mjs — screenshots of the live sites, captured October 2026.
// Static imports give next/image intrinsic dimensions and base-path-aware URLs.
import type { ProjectImages } from "@/types/project";

${imports}
export const projectImages: Record<string, ProjectImages> = {
${entries}};
`,
);
console.log("Wrote src/data/project-images.ts");
